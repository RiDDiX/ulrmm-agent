package agent

import (
	"os"
	"path/filepath"
	"runtime"
)

// writeFileSynced replaces path through a synced temp file: a power cut
// leaves the old content or the new one, never a cut file. The temp name is
// unique, two processes writing the same path do not mix their bytes.
func writeFileSynced(path string, b []byte, mode os.FileMode) error {
	f, err := os.CreateTemp(filepath.Dir(path), filepath.Base(path)+".*.tmp")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer os.Remove(tmp)
	if _, err = f.Write(b); err == nil {
		err = f.Sync()
	}
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Chmod(tmp, mode)
	}
	if err == nil {
		err = os.Rename(tmp, path)
	}
	if err == nil {
		syncDir(filepath.Dir(path))
	}
	return err
}

// syncDir makes a rename in dir survive a power cut. Windows cannot sync a
// directory; errors change nothing for the caller, the file itself is synced.
func syncDir(dir string) {
	if runtime.GOOS == "windows" {
		return
	}
	if d, err := os.Open(dir); err == nil {
		_ = d.Sync()
		d.Close()
	}
}
